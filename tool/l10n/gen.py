# Generates lib/l10n/translations.dart:  python tool/l10n/gen.py
import re, sys
import os
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
from base import EN, EL
from langs_a import TR, DE, FR, ES, IT
from langs_b import PT, RU, BG, AR, ZH
import rules_a, rules_b
from botnames import EXTRA

def parse(block):
    d = {}
    for line in block.strip().split('\n'):
        k, v = line.split('=', 1)
        assert k not in d, k
        d[k] = v
    return d

langs = {'el': EL, 'en': EN, 'tr': TR, 'de': DE, 'fr': FR, 'es': ES, 'it': IT, 'pt': PT, 'ru': RU, 'bg': BG, 'ar': AR, 'zh': ZH}
tables = {k: parse(v) for k, v in langs.items()}
import phase2_a, phase2_b, phase2_c, phase3, phase4
P2 = dict(phase2_a.P2); P2.update(phase2_b.P2)
for _k, _v in list(phase2_c.P2.items()) + list(phase3.P2.items()) + list(phase4.P2.items()):
    P2[_k] = P2[_k].rstrip('\n') + '\n' + _v.strip('\n')
for k in langs:
    extra = parse(P2[k])
    clash = set(extra) & set(tables[k])
    assert not clash, (k, clash)
    tables[k].update(extra)
# The pile game now scores exactly like the sum game: same tutorial text.
for _c in tables:
    tables[_c]['tut_score_b'] = tables[_c]['tut_scoreSums_b']
keys = list(tables['en'].keys())
ph = lambda s: sorted(set(re.findall(r'\{(\w+)\}', s)))
for code, t in tables.items():
    missing = [k for k in keys if k not in t]
    extra = [k for k in t if k not in keys]
    assert not missing and not extra, (code, missing, extra)
    for k in keys:
        assert ph(t[k]) == ph(tables['en'][k]), (code, k, t[k])

import rules_base
rules = dict(rules_base.RULES)
rules.update(rules_a.RULES); rules.update(rules_b.RULES)
# Dealing (section 2) and Points (section 6) come from rules_v2: the house
# scoring (10♦ 3, A 1, J 1, 2♣ 2, most cards 3), the kapak altı and the void deal.
import rules_v2
for code in langs:
    assert set(rules_v2.T[code]) == set(rules_v2.T['en']), code
    for v in ('pile', 'sums'):
        sec = list(rules[code][v])
        sec[1] = (sec[1][0], rules_v2.dealing(code, v))
        sec[5] = (sec[5][0], rules_v2.points(code, v))
        rules[code] = dict(rules[code], **{v: sec})
for code in langs:
    for v in ('pile', 'sums'):
        assert len(rules[code][v]) == 8, (code, v, len(rules[code][v]))

names = {'el': 'Ελληνικά', 'en': 'English', 'tr': 'Türkçe', 'de': 'Deutsch', 'fr': 'Français', 'es': 'Español',
         'it': 'Italiano', 'pt': 'Português', 'ru': 'Русский', 'bg': 'Български', 'ar': 'العربية', 'zh': '中文'}
bots = {'el': ['Γιώργος', 'Νίκος', 'Μαρία', 'Ελένη'], 'en': ['Giorgos', 'Nikos', 'Maria', 'Eleni'],
        'tr': ['Ahmet', 'Mehmet', 'Ayşe', 'Elif'], 'de': ['Jonas', 'Lukas', 'Anna', 'Lena'],
        'fr': ['Louis', 'Hugo', 'Emma', 'Léa'], 'es': ['Pablo', 'Javier', 'Lucía', 'Sofía'],
        'it': ['Marco', 'Luca', 'Giulia', 'Sofia'], 'pt': ['João', 'Pedro', 'Maria', 'Ana'],
        'ru': ['Иван', 'Дмитрий', 'Анна', 'Мария'], 'bg': ['Георги', 'Иван', 'Мария', 'Елена'],
        'ar': ['أحمد', 'عمر', 'ليلى', 'مريم'], 'zh': ['小明', '阿强', '小红', '小美']}

for _c in bots:
    bots[_c] = bots[_c] + EXTRA[_c]
    assert len(bots[_c]) == 40 and len(set(bots[_c])) == 40, (_c, len(bots[_c]))

def q(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$').replace('\n', '\\n') + "'"

out = ['// GENERATED by tool/l10n/gen.py from the tables in tool/l10n/. Do not edit by hand.',
       '// ignore_for_file: lines_longer_than_80_chars', '',
       '/// Native names of the supported languages.',
       'const Map<String, String> kLanguageNames = <String, String>{']
for c in langs: out.append(f'  {q(c)}: {q(names[c])},')
out += ['};', '', '/// Computer player names per language.', 'const Map<String, List<String>> kBotNames = <String, List<String>>{']
for c in langs: out.append(f'  {q(c)}: <String>[' + ', '.join(q(n) for n in bots[c]) + '],')
out += ['};', '', '/// UI texts per language; {name} placeholders are filled in by Strings.',
        'const Map<String, Map<String, String>> kTranslations = <String, Map<String, String>>{']
for c in langs:
    out.append(f'  {q(c)}: <String, String>{{')
    for k in keys: out.append(f'    {q(k)}: {q(tables[c][k])},')
    out.append('  },')
out += ['};', '', '/// Rules screen sections (title, body) per language and variant (pile / sums).',
        'const Map<String, Map<String, List<List<String>>>> kRules = <String, Map<String, List<List<String>>>>{']
for c in langs:
    out.append(f'  {q(c)}: <String, List<List<String>>>{{')
    for v in ('pile', 'sums'):
        out.append(f'    {q(v)}: <List<String>>[')
        for title, body in rules[c][v]:
            out.append(f'      <String>[{q(title)}, {q(body)}],')
        out.append('    ],')
    out.append('  },')
out += ['};', '']
open(os.path.join(ROOT, 'lib', 'l10n', 'translations.dart'), 'w', encoding='utf-8').write('\n'.join(out))
print(len(keys), 'keys,', len(langs), 'languages')
